export function formatInsightDate(value: string) {
  return new Intl.DateTimeFormat('zh-CN', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date(value)).replaceAll('/', '.')
}

export function getFallbackInsight(slug: string) {
  return fallbackInsights.find((item) => item.slug === slug)
}
